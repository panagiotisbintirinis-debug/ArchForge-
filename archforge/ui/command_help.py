def describe(action):
    """The explanation of a command (see the module docstring), or ''."""
    text = action.text().replace("&&", "&")
    for phrase, words in HELP:
        if phrase in text:
            return words
    for own in (action.toolTip(), action.statusTip()):
        own = (own or "").replace("&&", "&").strip()
        if own and own.replace("&", "") not in (text, text.replace("&", "")) and not own.startswith("<"):
            return own
    for part in reversed(str(action.property(PATH_PROPERTY) or "").split(" ▸ ")[1:]):   # deepest section first
        if part.replace("&&", "&") in SECTION_HELP:
            return SECTION_HELP[part.replace("&&", "&")]
    return ""


def card_html(action):
    name = html.escape(action.text().replace("&&", "&"))
    lines = [f"<b style='font-size:13px'>{name}</b>"]
    words = describe(action)
    if words:
        lines.append(f"<div style='margin-top:4px'>{html.escape(words)}</div>")
    extra = []
    if not action.shortcut().isEmpty():
        extra.append(f"Συντόμευση: <b>{html.escape(action.shortcut().toString())}</b>")
    path = str(action.property(PATH_PROPERTY) or "")
    if path:
        extra.append(html.escape(path))
    if extra:
        lines.append(f"<div style='margin-top:6px; color:#6a7686'>{' · '.join(extra)}</div>")
    return "".join(lines)


class RichTip(QFrame):
    """The card: the icon large, then the text."""

    def __init__(self):
        super().__init__(None, Qt.WindowType.ToolTip | Qt.WindowType.FramelessWindowHint)
        self.setObjectName("rich_tip")
        self.setStyleSheet("#rich_tip{background:#ffffff;border:1px solid #c9d2de;border-radius:6px}"
                           "QLabel{color:#283e5c;font-size:12px}")
        h = QHBoxLayout(self); h.setContentsMargins(10, 8, 12, 8); h.setSpacing(10)
        self.icon = QLabel(); self.icon.setFixedSize(48, 48); h.addWidget(self.icon, 0, Qt.AlignmentFlag.AlignTop)
        v = QVBoxLayout(); v.setContentsMargins(0, 0, 0, 0); h.addLayout(v)
        self.text = QLabel(); self.text.setWordWrap(True); self.text.setTextFormat(Qt.TextFormat.RichText)
        self.text.setMaximumWidth(320); self.text.setMinimumWidth(180); v.addWidget(self.text)
        self.action = None
        self._timer = QTimer(self); self._timer.setSingleShot(True); self._timer.timeout.connect(self.hide)

    def show_for(self, action, at):
        self.action = action
        icon = action.icon()
        self.icon.setVisible(not icon.isNull())
        if not icon.isNull():
            self.icon.setPixmap(icon.pixmap(48, 48))
        self.text.setText(card_html(action))
        self.adjustSize()
        screen = QApplication.screenAt(at) or QApplication.primaryScreen()
        pos = at + QPoint(16, 20)
        if screen is not None:
            g = screen.availableGeometry()
            pos.setX(min(pos.x(), g.right() - self.width() - 4)); pos.setY(min(pos.y(), g.bottom() - self.height() - 4))
        self.move(pos); self.show(); self.raise_()
        self._timer.start(15000)


class _Hover(QObject):
    """Application filter: a tooltip asked over a menu command or a command button shows the card instead."""

    def __init__(self, window):
        super().__init__(window)
        self.window = window
        self.tip = RichTip()

    def eventFilter(self, obj, event):
        t = event.type()
        if t == QEvent.Type.ToolTip:
            action = None
            if isinstance(obj, QMenu):
                action = obj.actionAt(event.pos())
                if action is not None and action.menu() is not None:
                    action = None
            elif isinstance(obj, QToolButton) and obj.defaultAction() is not None:
                action = obj.defaultAction()
            if action is not None and action.text():
                self.tip.show_for(action, event.globalPos())
                return True
            self.tip.hide()
        elif t in (QEvent.Type.Leave, QEvent.Type.MouseButtonPress, QEvent.Type.Hide, QEvent.Type.Wheel,
                   QEvent.Type.KeyPress) and self.tip.isVisible():
            self.tip.hide()
        elif t == QEvent.Type.MouseMove and isinstance(obj, QMenu) and self.tip.isVisible():
            if obj.actionAt(event.position().toPoint()) is not self.tip.action:
                self.tip.hide()
        return False


def mark_paths(window):
    """Each command of the menu bar remembers where it lives (the card's last line)."""
    def walk(menu, path):
        menu.setToolTipsVisible(True)                 # QMenu sends tooltip events only when this is on
        for a in menu.actions():
            if a.isSeparator() or not a.text():
                continue
            p = path + [a.text().replace("&&", "&")]
            if a.menu() is not None:
                walk(a.menu(), p)
            elif not a.property(PATH_PROPERTY):
                a.setProperty(PATH_PROPERTY, " ▸ ".join(path))
    for top in window.menuBar().actions():
        if top.menu() is not None:
            walk(top.menu(), [top.text().replace("&&", "&")])
    for a in getattr(window, "_quick_actions", ()):
        if not a.property(PATH_PROPERTY):
            a.setProperty(PATH_PROPERTY, "Πάντα ορατά (πρώτη γραμμή)")


_ACTIVE = []


def install(window):
    """One filter for the application (the newest window's); it goes away with its window."""
    mark_paths(window)
    app = QApplication.instance()
    for old in _ACTIVE:
        try:
            app.removeEventFilter(old); old.tip.hide()
        except RuntimeError:
            pass
    _ACTIVE.clear()
    hover = _Hover(window)
    app.installEventFilter(hover)
    _ACTIVE.append(hover)
    window._command_help = hover
    return hover
