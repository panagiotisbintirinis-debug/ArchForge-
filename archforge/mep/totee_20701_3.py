MONTHS = ("Ιανουάριος", "Φεβρουάριος")


def winter_design(city):
    """``(°C, source text)`` of a city's winter design temperature (DB 1 %), or None when it is in neither table."""
    if city in TABLE_2_1:
        return TABLE_2_1[city][0], f"{SOURCE}, Πίνακας 2.1, DB 1 %"
    if city in ESTIMATE_2_1:
        value, mean_min, abs_min, month, partial = ESTIMATE_2_1[city]
        note = " — λίγα έτη μετρήσεων (*)" if partial else ""
        g = lambda v: f"{v:g}".replace(".", ",")
        return value, (f"{SOURCE}, §2.1: μέσος όρος Πίν. 3.4 ({g(mean_min)}) και 3.6 ({g(abs_min)}), {MONTHS[month]}"
                       f"{note}")
    return None


def altitude_corrected(t_ref, alt_ref, alt_site):
    """§2.3, εξ. 2.1: the station's temperature moved to the site's altitude (−6,5 °C per 1000 m)."""
    return float(t_ref) - 6.5 * (float(alt_site) - float(alt_ref)) / 1000.0
