def base_case(kind, walls, slab, opening):
    """The code of Πίνακας 15 for a thermal bridge type, without the α/β/γ variants (None when it has no row)."""
    cat = CATEGORY_OF.get(kind)
    case_walls = {"ext": 1, "int": 2, "frame": 3}[walls]
    if cat in (1, 2, 3, 8, 10):
        return f"15.{cat}.{case_walls}"
    if cat == 4:
        return f"15.4.{ {('ext', 'top'): 1, ('ext', 'bottom'): 2, ('int', 'top'): 3, ('int', 'bottom'): 4, ('frame', 'top'): 5, ('frame', 'bottom'): 6}[(walls, slab)] }"
    if cat == 9:                                          # 9: core insulation stands for the frame scheme
        return f"15.9.{ {('int', 'top'): 1, ('ext', 'bottom'): 2, ('ext', 'top'): 3, ('int', 'bottom'): 4, ('frame', 'top'): 5, ('frame', 'bottom'): 6}[(walls, slab)] }"
    if cat == 11:
        return f"15.11.{ {'same': 1, 'apart': 2, 'wrapped': 3}[opening] }"
    if cat == 12:
        if kind == "threshold":
            return "15.12.4"
        return f"15.12.{ {'same': 1, 'apart': 2, 'wrapped': 3}[opening] }"
    return None


def cases(kind):
    """``[(code, text, ψ)]`` of the type's category — the base cases and their α/β/γ, in the table's order."""
    cat = CATEGORY_OF.get(kind)
    return [(code, text, psi) for code, (c, text, psi) in TABLE_15.items() if c == cat]


def entry(code):
    """``{"psi", "code", "source"}`` of one row, ready for the project's catalogue."""
