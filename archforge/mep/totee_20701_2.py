def row_text(code):
    desc, rho, lam, hi = TABLE_2[code]
    value = (f"{lam:.3f}" if hi is None else f"{lam:.3f}–{hi:.3f}").replace(".", ",")
    return f"{code.split('-')[0]} {desc}" + (f", {rho} kg/m³" if rho else "") + f": λ {value}"


def row_values(code, pick="upper"):
    """``{"conductivity", "density", "source"}`` of one row for a material's data; a range gives its upper end
    (the safer side for heat loss) unless ``pick="lower"`` — the product's data sheet still decides."""
    desc, rho, lam, hi = TABLE_2[code]
    value = lam if hi is None else (hi if pick == "upper" else lam)
    src = f"{TABLE_2_SOURCE} · {code.split('-')[0]} {desc}" + (f", {rho} kg/m³" if rho else "")
    if hi is not None:
        src += f" (εύρος {lam:g}–{hi:g}· το ακριβές από το φύλλο του προϊόντος)".replace(".", ",")
    return {"conductivity": value, "density": rho, "source": src}
