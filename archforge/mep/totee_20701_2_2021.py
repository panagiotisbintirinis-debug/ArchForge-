def u_max(element, zone, renovation=False):
    """Μέγιστο U [W/(m²K)]: Πίν. 5α (νέο κτίριο) ή 5β (ριζική ανακαίνιση), None χωρίς ζώνη."""
    if zone not in ZONES or element not in TABLE_5:
        return None
    return TABLE_5[element][2 if renovation else 1][ZONES.index(zone)]


def u_max_project(doc, element):
    """``(U max, «ΤΟΤΕΕ 20701-2/2021 Πίν. 5α (νέο κτίριο)»)`` for the project's zone and type, or ``(None, None)``."""
    from archforge.mep.design_climate import zone
    from archforge.project.brief import is_renovation
    z = zone(doc)
    reno = bool(is_renovation(doc))
    v = u_max(element, z, reno)
    if v is None:
        return None, None
    return v, f"ζώνης {z}, {SOURCE} Πίν. {'5β (ριζική ανακαίνιση)' if reno else '5α (νέο κτίριο)'}"


# ------------------------------------------------------------------ σχέσεις 2.10, 2.13–2.15, 2.17–2.19

def uw(af, ag, lg, uf, ug, psi, usb=0.0, asb=0.0):
    """Σχέσεις 2.10 / 2.17: (Uf·Af + Ug·Ag + Ψg·lg + Usb·Asb) / (Af + Ag)."""
    if af + ag <= 0:
        raise ValueError("κούφωμα χωρίς εμβαδό")
    return (uf * af + ug * ag + psi * lg + usb * asb) / (af + ag)


def horizontal(u):
    """Σχέσεις 2.13–2.15: U σε οριζόντια θέση (κλίση ≤ 30°)."""
    return 1.0 / (1.0 / u - 0.03)


def with_shutter(uw_, rrb):
    """Σχέση 2.18: Uw,rb με ρολό / εξώφυλλο κλειστό."""
    return 1.0 / (1.0 / uw_ + rrb)


def corrected(uw_, rrb, frb=FRB):
    """Σχέση 2.19: Uw,διορθ = Uw·(1 − frb) + Uw,rb·frb (για τη μελέτη ενεργειακής απόδοσης, όχι για τον έλεγχο επάρκειας)."""
    return uw_ * (1 - frb) + with_shutter(uw_, rrb) * frb
