def glazing_key(row, gas):
    return f"{row}|{gas}"


def glazing(key):
    """``(row, gas, Ug, label)`` of a glazing key «2|le05|4-16-4|argon», or None."""
    parts = str(key or "").split("|")
    if len(parts) != 4:
        return None
    row, gas = "|".join(parts[:3]), parts[3]
    if row not in TABLE_9 or gas not in _G:
        return None
    desc, eps, dims, ug = TABLE_9[row]
    return row, gas, ug[gas], f"{dims} {GAS_LABEL[gas]} · {desc} ε {eps} · Ug {ug[gas]:g}".replace(".", ",")


def glazing_short(key):
    """«4-16-4 αργό · low-e ε ≤0,05» — for narrow columns."""
    g = glazing(key)
    if g is None:
        return ""
    n, coating, dims = g[0].split("|")
    coat = {"none": "χωρίς low-e", "le10": "low-e ε ≤0,10", "le05": "low-e ε ≤0,05"}[coating]
    return f"{'Τριπλή' if n == '3' else 'Διπλή'} {dims} {GAS_LABEL[g[1]]} · {coat}"


def glazing_choices():
    return [(glazing_key(row, gas), glazing(glazing_key(row, gas))[3]) for row in TABLE_9 for gas in _G]


