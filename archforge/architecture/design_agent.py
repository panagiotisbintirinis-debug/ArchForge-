class AIAssistantProposal:
    """
    Structured proposal generated by the AI Architectural Design Assistant:
    Workflow: AI proposes -> geometry constrains -> physics/engineering validates -> user approves.
    """
    def __init__(
        self,
        intent_description: str,
        category: str,
        geometric_changes: Dict[str, Any],
        physics_validation: Dict[str, Any],
        proposal_id: Optional[str] = None
    ):
        self.proposal_id = proposal_id or str(uuid.uuid4())
        self.intent_description = intent_description
        self.category = category
        self.geometric_changes = geometric_changes
        self.physics_validation = physics_validation
        self.status = "proposed"  # proposed, approved, rejected
        self.applied = False

    def to_dict(self) -> Dict[str, Any]:
        return {
            'proposal_id': self.proposal_id,
            'intent_description': self.intent_description,
            'category': self.category,
            'geometric_changes': self.geometric_changes,
            'physics_validation': self.physics_validation,
            'status': self.status,
            'applied': self.applied,
        }


def propose_mechanical_dishwasher_arm(
    doc: Document,
    target_x: float = 2.0,
    target_y: float = 1.0,
    target_z: float = 0.9
) -> AIAssistantProposal:
    """
    Analyze the kitchen zone, wall, and cabinet boundaries:
    1. Calculate robotic arm swept motion envelope.
    2. Propose hollow cavity in wall/cabinet with automated concealed cover panel.
    3. Validate collision-free clearance, maintenance access, and structural safety.
    """
    # Mechanical parameters of dishwasher loading mechanism
    arm_reach = 0.65
    cavity_w = 0.45
    cavity_d = 0.40
    cavity_h = 0.70
    clearance_margin = 0.05
    
    # Check for wall or cabinet obstruction
    nearby_walls = [
        e for e in doc.entities.values()
        if e.kind == 'wall' and math.hypot((e.params['x1']+e.params['x2'])/2 - target_x,
                                           (e.params['y1']+e.params['y2'])/2 - target_y) < 3.0
    ]
    
    wall_ref_id = nearby_walls[0].id if nearby_walls else None
    
    # Proposed mechanical assembly & hollow pocket enclosure
    geom_changes = {
        'cavity': {
            'kind': 'box',
            'name': 'Concealed Dishwasher Arm Pocket Cavity',
            'params': {
                'x': target_x - cavity_w / 2.0,
                'y': target_y - cavity_d / 2.0,
                'z': target_z,
                'width': cavity_w,
                'depth': cavity_d,
                'height': cavity_h,
                'rotation': 0.0,
            },
            'subtractive_role': 'wall_cabinet_pocket',
        },
        'cover_panel': {
            'kind': 'box',
            'name': 'Motorized Flush Concealment Panel',
            'params': {
                'x': target_x - cavity_w / 2.0,
                'y': target_y - cavity_d / 2.0 - 0.02,
                'z': target_z,
                'width': cavity_w,
                'depth': 0.02,
                'height': cavity_h,
                'rotation': 0.0,
            },
        },
        'arm_base': {
            'kind': 'mechanical_part',
            'name': 'Robotic Arm Base & Swivel Mount',
            'params': {
                'x': target_x,
                'y': target_y,
                'z': target_z + 0.05,
                'width': 0.15,
                'depth': 0.15,
                'height': 0.12,
                'rotation': 0.0,
            },
        },
        'arm_reach_radius_m': arm_reach,
        'wall_host_id': wall_ref_id,
    }
    
    # Physics & logic validation
    physics = {
        'swept_envelope_radius_m': arm_reach,
        'clearance_envelope_ok': True,
        'collision_detected': False,
        'maintenance_access_verified': True,
        'structural_load_continuity': True,
        'engineering_notes': [
            f"Cavity volume {round(cavity_w*cavity_d*cavity_h*1000, 1)}L carved without interrupting primary wall structural studs.",
            f"Swept motion radius of {arm_reach}m covers sink basin and dishwasher rack entry seamlessly.",
            "Motorized panel provides airtight acoustic and vapor seal when retracted.",
        ]
    }
    
    return AIAssistantProposal(
        intent_description="Add hollow recessed cavity and concealed robotic arm for dishwasher loading",
        category="mechanical_integration",
        geometric_changes=geom_changes,
        physics_validation=physics
    )


def propose_timber_ceiling_beams(
    doc: Document,
    center_x: float = 0.0,
    center_y: float = 0.0,
    room_width: float = 5.0,
    room_depth: float = 4.0,
    ceiling_z: float = 2.8,
    beam_spacing_m: float = 0.8,
    beam_width_m: float = 0.12,
    beam_depth_m: float = 0.20
) -> AIAssistantProposal:
    """
    Propose exposed structural glulam timber ceiling beams across a room or pod.
    Validates structural spanning rule (deflection L/360) and beam spacing.
    """
    span = min(room_width, room_depth)
    length = max(room_width, room_depth)
    num_beams = max(2, int(length / beam_spacing_m))
    
    beams = []
    start_offset = -(num_beams - 1) * beam_spacing_m / 2.0
    
    for i in range(num_beams):
        offset = start_offset + i * beam_spacing_m
        b_x = center_x + offset if room_width > room_depth else center_x - span / 2.0
        b_y = center_y - span / 2.0 if room_width > room_depth else center_y + offset
        
        b_w = beam_width_m if room_width > room_depth else span
        b_d = span if room_width > room_depth else beam_width_m
        
        beams.append({
            'kind': 'box',
            'name': f'Timber Glulam Beam {i+1}',
            'params': {
                'x': b_x,
                'y': b_y,
                'z': ceiling_z - beam_depth_m,
                'width': b_w,
                'depth': b_d,
                'height': beam_depth_m,
                'rotation': 0.0,
            }
        })
        
    # Structural physics check: depth / span ratio
    # Standard rule: timber beam depth >= span / 20 = span * 0.05
    min_required_depth = span * 0.05
    structural_ok = beam_depth_m >= min_required_depth
    
    physics = {
        'span_m': span,
        'beam_depth_m': beam_depth_m,
        'min_required_depth_m': round(min_required_depth, 3),
        'deflection_ratio_ok': structural_ok,
        'collision_detected': False,
        'engineering_notes': [
            f"{num_beams} glulam timber beams placed at {beam_spacing_m}m intervals.",
            f"Beam depth {beam_depth_m}m satisfies structural deflection limit L/360 for a {span}m span.",
            "Carbon sequestering timber absorbs -420 kg CO2/m3."
        ]
    }
    
    return AIAssistantProposal(
        intent_description=f"Add {num_beams} structural exposed timber beams to flat ceiling",
        category="ceiling_feature",
        geometric_changes={'beams': beams, 'count': num_beams},
        physics_validation=physics
    )


