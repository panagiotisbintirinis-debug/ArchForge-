def propose_rotational_facade_louvers(
    doc: Document,
    target_x: float = 3.5,
    target_y: float = -1.0,
    target_z: float = 1.2,
    panel_height: float = 2.4,
    panel_width: float = 3.0,
    louver_count: int = 5,
) -> AIAssistantProposal:
    """
    Propose rotatable aerodynamic/solar kinetic facade louvers.
    - Synchronized revolute joints pivoting 0° to 135°.
    - Solar path tracking and wind-shedding mode.
    - Embedded flush bearings in exterior window/wall reveals.
    """
    louvers = []
    spacing = panel_width / max(1, louver_count)
    for i in range(louver_count):
        lx = target_x - panel_width/2 + (i + 0.5) * spacing
        louvers.append({
            'kind': 'mechanical_part',
            'name': f'Rotational Kinetic Louver Blade #{i+1}',
            'params': {
                'x': lx,
                'y': target_y,
                'z': target_z,
                'width': spacing * 1.05,
                'depth': 0.04,
                'height': panel_height,
                'rotation': 0.0
            }
        })
        
    geom_changes = {
        'louvers': louvers,
        'revolute_joint': {
            'kind': 'mechanical_joint',
            'name': 'Facade Louver Synchronous Revolute Joint',
            'params': {
                'joint_type': 'revolute',
                'axis': [0.0, 0.0, 1.0],
                'anchor': [target_x, target_y, target_z],
                'min_value': 0.0,
                'max_value': 135.0,
                'value': 45.0
            }
        }
    }
    
    physics = {
        'rotation_range_deg': [0.0, 135.0],
        'daylight_lux_modulation': '200 to 4500 lux',
        'aerodynamic_drag_reduction_pct': 48.0,
        'clearance_envelope_ok': True,
        'structural_load_transfer': True,
        'engineering_notes': [
            f"{louver_count} kinetic vertical louvers modulate solar heat gain coefficient (SHGC 0.15 to 0.72).",
            "Continuous stainless-steel pivot pins sealed against coastal moisture infiltration.",
            "Integrated into building envelope without thermal bridging."
        ]
    }
    
    return AIAssistantProposal(
        intent_description=f"Add kinetic rotational facade louvers ({louver_count} blades, 0°-135° rotation)",
        category="rotational_louvers",
        geometric_changes=geom_changes,
        physics_validation=physics
    )


def apply_ai_proposal(doc: Document, proposal: AIAssistantProposal) -> List[str]:
    """
    Execute the proposed changes upon user approval, returning list of created entity IDs.
    """
    created_ids = []
    
    if proposal.category == 'mechanical_integration':
        # Add cavity and mechanism entities
        for key in ('cavity', 'cover_panel', 'arm_base'):
            raw = proposal.geometric_changes.get(key)
            if raw and isinstance(raw, dict) and 'kind' in raw:
                e = Entity(kind=raw['kind'], name=raw['name'], params=raw['params'])
                eid = doc.add(e)
                created_ids.append(eid)
                
    elif proposal.category == 'kinematic_pergola':
        # Create base anchor beam/rail part
        rail_base = Entity('mechanical_part', {
            'x': proposal.geometric_changes['guide_rails'][0]['params']['x'],
            'y': proposal.geometric_changes['guide_rails'][0]['params']['y'],
            'z': proposal.geometric_changes['guide_rails'][0]['params']['z'],
            'width': proposal.geometric_changes['guide_rails'][0]['params']['width'],
            'depth': 0.15,
            'height': 0.15,
            'rotation': 0.0,
        }, name='Pergola Structural Anchor Rail')
        parent_id = doc.add(rail_base)
        created_ids.append(parent_id)

        # Create sliding carriage part
        car = proposal.geometric_changes.get('sliding_carriage')
        car_entity = Entity(kind=car['kind'], name=car['name'], params=car['params'])
        child_id = doc.add(car_entity)
        created_ids.append(child_id)

        # Create prismatic joint
        joint_dict = copy.deepcopy(proposal.geometric_changes['prismatic_joint'])
        joint_dict['params']['parent_part'] = parent_id
        joint_dict['params']['child_part'] = child_id
        joint_entity = Entity(kind=joint_dict['kind'], name=joint_dict['name'], params=joint_dict['params'])
        created_ids.append(doc.add(joint_entity))

    elif proposal.category == 'rotational_louvers':
        # Base mullion anchor frame
        mullion = Entity('mechanical_part', {
            'x': proposal.geometric_changes['louvers'][0]['params']['x'],
            'y': proposal.geometric_changes['louvers'][0]['params']['y'],
            'z': proposal.geometric_changes['louvers'][0]['params']['z'],
            'width': 0.1,
            'depth': 0.1,
            'height': proposal.geometric_changes['louvers'][0]['params']['height'],
            'rotation': 0.0,
        }, name='Facade Kinetic Header Mullion')
        parent_id = doc.add(mullion)
        created_ids.append(parent_id)

        louvers = proposal.geometric_changes.get('louvers', [])
        for idx, l in enumerate(louvers):
            l_entity = Entity(kind=l['kind'], name=l['name'], params=l['params'])
            child_id = doc.add(l_entity)
            created_ids.append(child_id)

            if idx == 0:
                joint_dict = copy.deepcopy(proposal.geometric_changes['revolute_joint'])
                joint_dict['params']['parent_part'] = parent_id
                joint_dict['params']['child_part'] = child_id
                joint_entity = Entity(kind=joint_dict['kind'], name=joint_dict['name'], params=joint_dict['params'])
                created_ids.append(doc.add(joint_entity))
                
    elif proposal.category == 'ceiling_feature':
        beams = proposal.geometric_changes.get('beams', [])
        for b in beams:
            e = Entity(kind=b['kind'], name=b['name'], params=b['params'])
            created_ids.append(doc.add(e))
            
        panel = proposal.geometric_changes.get('panel')
        if panel and isinstance(panel, dict):
            e = Entity(kind=panel['kind'], name=panel['name'], params=panel['params'])
            created_ids.append(doc.add(e))
            
    proposal.status = "approved"
    proposal.applied = True
    return created_ids
